    function switchSecTab(tab) {
      const usableWrap = document.getElementById('sec-table-usable-wrap');
      const purgedWrap = document.getElementById('sec-table-purged-wrap');
      const btnUsable = document.getElementById('tab-btn-usable');
      const btnPurged = document.getElementById('tab-btn-purged');

      if (tab === 'usable') {
        usableWrap.classList.remove('hidden');
        purgedWrap.classList.add('hidden');
        btnUsable.className = 'px-3 py-1 rounded-lg text-xs font-bold bg-cyan-500/20 text-cyan-300 border border-cyan-500/40';
        btnPurged.className = 'px-3 py-1 rounded-lg text-xs font-bold bg-slate-800 text-slate-400 border border-slate-700 hover:text-white';
      } else {
        usableWrap.classList.add('hidden');
        purgedWrap.classList.remove('hidden');
        btnPurged.className = 'px-3 py-1 rounded-lg text-xs font-bold bg-rose-500/20 text-rose-300 border border-rose-500/40';
        btnUsable.className = 'px-3 py-1 rounded-lg text-xs font-bold bg-slate-800 text-slate-400 border border-slate-700 hover:text-white';
      }
    }
    window.switchSecTab = switchSecTab;

    async function fetchSecurityInventory() {
      try {
        const res = await fetch('/api/security-inventory');
        if (!res.ok) return;
        const data = await res.json();
        currentSecInventory = data;
        renderSecurityUI(data);
      } catch (e) {
        console.warn('[SecurityVault] Fetch failed:', e);
      }
    }
    window.fetchSecurityInventory = fetchSecurityInventory;

    function renderSecurityUI(data) {
      const s = data.summary || {};
      document.getElementById('sec-usable-count').innerText = (s.usable_active_count || 0) + '건';
      document.getElementById('sec-keys-count').innerText = (s.masked_keys_count || 0) + '건';
      document.getElementById('sec-purged-count').innerText = (s.purged_obsolete_count || 0) + '건';
      document.getElementById('sec-scan-time').innerText = '최근 스캔: ' + (data.scan_timestamp || '실시간');

      // 사용 가능 자산 테이블
      const uTbody = document.getElementById('sec-usable-tbody');
      uTbody.innerHTML = '';
      (data.usable_assets || []).forEach(a => {
        const tr = document.createElement('tr');
        tr.className = 'hover:bg-slate-900 transition';
        const isKey = a.category.includes('키');
        tr.innerHTML = `
          <td class="py-2 px-3 text-slate-400">${a.asset_id}</td>
          <td class="py-2 px-3"><span class="px-1.5 py-0.5 rounded text-[10px] ${isKey ? 'bg-cyan-500/20 text-cyan-300' : 'bg-purple-500/20 text-purple-300'}">${a.category}</span></td>
          <td class="py-2 px-3 text-white font-sans font-medium">${a.name}</td>
          <td class="py-2 px-3 ${isKey ? 'text-amber-300' : 'text-slate-300'}">${a.masked_preview} <span class="text-[9px] text-slate-500">[fp:${a.fingerprint}]</span></td>
          <td class="py-2 px-3 text-slate-400 font-sans">${a.location_hint}</td>
          <td class="py-2 px-3 text-emerald-400 font-bold">🟢 ${a.status}</td>
        `;
        uTbody.appendChild(tr);
      });

      // 폐기 완료 자산 테이블
      const pTbody = document.getElementById('sec-purged-tbody');
      pTbody.innerHTML = '';
      (data.purged_assets || []).forEach(p => {
        const tr = document.createElement('tr');
        tr.className = 'hover:bg-slate-900 transition';
        tr.innerHTML = `
          <td class="py-2 px-3 text-slate-400">${p.asset_id}</td>
          <td class="py-2 px-3 text-slate-300">${p.category}</td>
          <td class="py-2 px-3 text-rose-400 line-through font-sans">${p.name}</td>
          <td class="py-2 px-3 text-slate-500">${p.location_hint}</td>
          <td class="py-2 px-3 text-rose-300 font-bold">🗑️ ${p.action_taken}</td>
        `;
        pTbody.appendChild(tr);
      });
    }

    async function runSecurityAudit() {
      const btn = document.getElementById('btn-sec-audit');
      btn.disabled = true;
      btn.innerHTML = '<span>⏳ 전수 스캔 및 소각 중...</span>';
      try {
        const res = await fetch('/api/security-audit-run', { method: 'POST' });
        const data = await res.json();
        if (data.status === 'ok') {
          alert('🛡️ [노트북 전수 보안 감사 완료]\n• 유효 핵심 자산: ' + data.report.summary.usable_active_count + '건 (마스킹 키 ' + data.report.summary.masked_keys_count + '건)\n• 소각 완료: ' + data.report.summary.purged_obsolete_count + '건\n• GitHub 유출 위험도: 0.00% SAFE');
          renderSecurityUI(data.report);
        } else {
          alert('감사 오류: ' + data.message);
        }
      } catch (err) {
        alert('요청 오류: ' + err.message);
      } finally {
        btn.disabled = false;
        btn.innerHTML = '<span>🔄 노트북 전수 보안 재감사</span>';
      }
    }
    window.runSecurityAudit = runSecurityAudit;

