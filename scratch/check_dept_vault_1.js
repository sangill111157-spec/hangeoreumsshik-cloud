    async function saveSnsHandleToVault() {
      const platform = document.getElementById('sns-input-platform').value;
      const handle = document.getElementById('sns-input-handle').value.trim();
      const channel_url = document.getElementById('sns-input-url').value.trim();
      const btn = document.getElementById('btn-save-sns-vault');
      const receipt = document.getElementById('sns-vault-save-receipt');
      if (!handle) {
        alert('계정 핸들을 입력해주세요 (예: @boosterplaylist)');
        return;
      }
      if (btn) btn.innerHTML = '<span>⏳ 비밀금고 잠금 중...</span>';
      try {
        const res = await fetch('/api/sns-account-update', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ platform, handle, channel_url })
        });
        const result = await res.json();
        if (result.status === 'OK') {
          if (receipt) {
            receipt.classList.remove('hidden');
            receipt.innerText = `✅ [${platform.toUpperCase()} 금고 잠금 완료] 마스킹: ${result.data?.handle_masked || handle} (로컬 비밀금고 격리 완료)`;
          }
          await fetchSnsInventory();
          document.getElementById('sns-input-handle').value = '';
          document.getElementById('sns-input-url').value = '';
        } else {
          alert('저장 실패: ' + (result.message || '오류'));
        }
      } catch (err) {
        alert('통신 에러: ' + err.message);
      } finally {
        if (btn) btn.innerHTML = '<span>🔐 비밀금고에 안전 저장</span>';
      }
    }
    window.saveSnsHandleToVault = saveSnsHandleToVault;

