def run(items=None):
    items = items or drafts()
    r1 = {i["id"]: review(i, items) for i in items}
    fixed, acts = [], {}
    for it in items:
        n, a = json.loads(json.dumps(it)), []
        for code in dict.fromkeys(c for cid in SIX for c in r1[it["id"]]["critics"][cid]["codes"]):
            FIXES[code][1](n); a.append(f"[{code}] {FIXES[code][0]}")
        fixed.append(n); acts[it["id"]] = a
    rows = []
    for it, n in zip(items, fixed):
        a, b = r1[it["id"]], review(n, fixed)
        rows.append(dict(id=it["id"], title=it["title"], round1_score=a["total"], round1_verdict=a["verdict"],
            round1_critics=a["critics"], auto_fix_actions=acts[it["id"]], round2_final_score=b["total"],
            round2_critic_scores={c: b["critics"][c]["score"] for c in b["critics"]}, round2_status="PASSED" if b["verdict"] == "APPROVED" else "STILL_REJECTED"))
    r1a, r2a = round(sum(r["round1_score"] for r in rows) / len(rows), 2), round(sum(r["round2_final_score"] for r in rows) / len(rows), 2)
    rep = dict(version=VERSION, organ=ORGAN, antibody=ANTIBODY, lock=LOCK, skill=SKILL, generated=datetime.now().isoformat(timespec="seconds"),
        council=RUTHLESS_CRITIC_COUNCIL_7, pass_line=PASS_LINE, round1_avg=r1a, round2_avg=r2a,
        round2_in_target_band_96_5_99_4=all(96.5 <= r["round2_final_score"] <= 100.0 for r in rows),
        status="ALL_PASSED" if all(r["round2_status"] == "PASSED" for r in rows) else "NOT_ALL_PASSED", items=rows)
    REPORT.write_text(json.dumps(rep, ensure_ascii=False, indent=2), encoding="utf-8")
    page = showcase(rep)
    for d in SHOW_DIRS: d.mkdir(parents=True, exist_ok=True); (d / SHOW_NAME).write_text(page, encoding="utf-8")
    return rep

