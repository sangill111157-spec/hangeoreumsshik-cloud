def clean_links(text):
    n = len(re.findall(BAD_LINK, text)); text = re.sub(BAD_LINK, "", text)
    for u in re.findall(r"https?://[^\s<>\"']+", text):
        if u != LIVE_URL: text = text.replace(u, ""); n += 1
    return text, n

def tg_call(tok, method, fields, files=None):
    url, hdr = f"https://api.telegram.org/bot{tok}/{method}", {}
    if files:
        b, body = uuid.uuid4().hex, b""
        for k, v in fields.items(): body += f'--{b}\r\nContent-Disposition: form-data; name="{k}"\r\n\r\n{v}\r\n'.encode()
        for k, (fn, data) in files.items(): body += f'--{b}\r\nContent-Disposition: form-data; name="{k}"; filename="{fn}"\r\nContent-Type: video/mp4\r\n\r\n'.encode() + data + b"\r\n"
        body += f"--{b}--\r\n".encode(); hdr = {"Content-Type": f"multipart/form-data; boundary={b}"}
    else: body = urllib.parse.urlencode(fields).encode()
    with urllib.request.urlopen(urllib.request.Request(url, body, hdr), timeout=120) as r: return json.load(r)

