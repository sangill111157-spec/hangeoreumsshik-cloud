# -*- coding: utf-8 -*-
"""
S1 Deploy YouTube Studio Branding (s1_deploy_youtube_branding.py)
Automates:
1. Assign distinct IDs to file inputs via evaluate
2. Upload Banner Image (#s1-file-banner) & click Done modal
3. Upload Avatar Image (#s1-file-avatar) & click Done modal
4. Upload Watermark Image (#s1-file-watermark) & select "Entire video"
5. Set English SEO Description with 33% Philanthropy Pledge
6. Click '게시 (Publish)' and verify
7. Capture screenshots at every step
"""

import sys
import json
import pathlib
import time
import s1_ego

try:
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
except Exception:
    pass

ROOT_DIR = pathlib.Path(__file__).resolve().parent
BRANDING_DIR = ROOT_DIR / "studio_vault" / "CHANNELS" / "04_US_SUNONE_AON" / "BRANDING_KIT"

AVATAR_FILE = (BRANDING_DIR / "avatar_800x800.png").resolve().as_posix()
BANNER_FILE = (BRANDING_DIR / "banner_2560x1440.png").resolve().as_posix()
WATERMARK_FILE = (BRANDING_DIR / "watermark_800x800.png").resolve().as_posix()

SCREENSHOT_BEFORE = (ROOT_DIR / "studio_vault" / "CHANNELS" / "04_US_SUNONE_AON" / "live_branding_step1_ready.png").resolve().as_posix()
SCREENSHOT_STAGED = (ROOT_DIR / "studio_vault" / "CHANNELS" / "04_US_SUNONE_AON" / "live_branding_step2_staged.png").resolve().as_posix()
SCREENSHOT_AFTER = (ROOT_DIR / "studio_vault" / "CHANNELS" / "04_US_SUNONE_AON" / "live_branding_step3_published.png").resolve().as_posix()
SCREENSHOT_PUBLIC = (ROOT_DIR / "studio_vault" / "CHANNELS" / "04_US_SUNONE_AON" / "live_branding_step4_public.png").resolve().as_posix()

DESCRIPTION_TEXT = """Welcome to SUN-ONE AON — Where Sound Awakens the Soul and Value Returns to the World.

Rooted in the timeless Eastern philosophy of "Sangseonyaksu" (上善若水: "The highest excellence is like water, benefiting all things without contending"), SUN-ONE AON is a global music label and cinematic sound sanctuary founded by Sangill Lee.

🌊 Our 33% Global Philanthropy Pledge:
We believe that true creative abundance flows outward. 33% of all streaming, licensing, and broadcast royalties generated by SUN-ONE AON are dedicated directly to global humanitarian initiatives, environmental restoration, and empowering underprivileged youth through music education.

🎵 Our Musical Universe:
• World-Class Cinematic Orchestral Anthems & Hybrid Soundtracks
• Mindful Acoustic Melodies & Hanok Heritage Harmony
• Euphoric Midnight Synthwave & Athletic Motivation Beats
• Healing 432Hz Soundscapes for Focus, Deep Work & Meditation

✨ Official Links & Distribution:
• Official DistroKid Music Label: SUN-ONE AON Records
• Worldwide Streaming: Spotify, Apple Music, YouTube Music, Amazon Music, Melon
• Channel Handle: @SUN-ONEAON

"Water nourishes all creations with quiet humility. We compose music to elevate the human spirit."

Executive Producer: Sangill Lee (이상일)
Label: SUN-ONE AON Records
Inquiries & Licensing: sangill111157@gmail.com"""

def run_branding_deployment():
    js = s1_ego.EGO_PRELUDE_JS + f"""
    let currentTask = null;
    try {{
      const task = await getTask(17);
      currentTask = task;
      const tabs = await task.tabs();
      const page = tabs[0].page;

      const results = {{
        avatar_uploaded: false,
        banner_uploaded: false,
        watermark_uploaded: false,
        watermark_entire_video_selected: false,
        description_set: false,
        publish_clicked: false,
        toast_message: "",
        public_url: "",
        channel_id: "UC4C_H80jcXzKV8ldAtmYMog",
        handle: "@SUN-ONEAON",
        errors: []
      }};

      const rawUrl = (typeof page.url === 'function') ? page.url() : (page.url || '');
      const currentUrl = (typeof rawUrl === 'string') ? rawUrl : (rawUrl.href || String(rawUrl));
      if (!currentUrl.includes("/editing/profile")) {{
        console.log("Navigating to editing/profile...");
        await page.goto("https://studio.youtube.com/channel/UC4C_H80jcXzKV8ldAtmYMog/editing/profile", {{ waitUntil: "networkidle", timeout: 45000 }});
        await page.waitForTimeout(3000);
      }}

      await page.screenshot({{ path: {json.dumps(SCREENSHOT_BEFORE)} }});

      // Helper to tag file inputs with distinct IDs
      async function tagFileInputs() {{
        return await page.evaluate(() => {{
          const inputs = document.querySelectorAll('input[type="file"]');
          if (inputs[0]) inputs[0].id = 's1-file-banner';
          if (inputs[1]) inputs[1].id = 's1-file-avatar';
          if (inputs[2]) inputs[2].id = 's1-file-watermark';
          return inputs.length;
        }});
      }}

      // Helper to click Done in modal
      async function clickDoneInModal() {{
        await page.waitForTimeout(2000);
        return await page.evaluate(() => {{
          const btns = Array.from(document.querySelectorAll('button, tp-yt-paper-button, ytcp-button, [role="button"]'));
          const doneBtn = btns.find(b => {{
            const t = (b.innerText || b.getAttribute('aria-label') || '').trim();
            return t === '완료' || t === 'Done' || b.id === 'done-button';
          }});
          if (doneBtn) {{
            doneBtn.click();
            return true;
          }}
          return false;
        }});
      }}

      let count = await tagFileInputs();
      console.log("Tagged file inputs count:", count);

      // 1. Upload Banner Image
      try {{
        console.log("Setting input files for Banner...");
        await page.setInputFiles('#s1-file-banner', {json.dumps(BANNER_FILE)});
        await page.waitForTimeout(2500);
        const doneBanner = await clickDoneInModal();
        console.log("Done clicked for banner:", doneBanner);
        results.banner_uploaded = true;
      }} catch (e) {{
        console.log("Banner upload error:", e.message);
        results.errors.push("Banner: " + e.message);
      }}

      await page.waitForTimeout(2000);
      await tagFileInputs();

      // 2. Upload Avatar Image
      try {{
        console.log("Setting input files for Avatar...");
        await page.setInputFiles('#s1-file-avatar', {json.dumps(AVATAR_FILE)});
        await page.waitForTimeout(2500);
        const doneAvatar = await clickDoneInModal();
        console.log("Done clicked for avatar:", doneAvatar);
        results.avatar_uploaded = true;
      }} catch (e) {{
        console.log("Avatar upload error:", e.message);
        results.errors.push("Avatar: " + e.message);
      }}

      await page.waitForTimeout(2000);
      await tagFileInputs();

      // 3. Upload Watermark Image
      try {{
        console.log("Setting input files for Watermark...");
        await page.setInputFiles('#s1-file-watermark', {json.dumps(WATERMARK_FILE)});
        await page.waitForTimeout(2500);
        const doneWatermark = await clickDoneInModal();
        console.log("Done clicked for watermark:", doneWatermark);
        results.watermark_uploaded = true;

        // Select '전체 동영상'
        await page.waitForTimeout(1000);
        const radioSelected = await page.evaluate(() => {{
          const radios = Array.from(document.querySelectorAll('tp-yt-paper-radio-button, input[type="radio"], [role="radio"]'));
          const entireRadio = radios.find(r => (r.innerText || '').includes('전체 동영상') || (r.innerText || '').includes('Entire video') || r.id.includes('entire'));
          if (entireRadio) {{
            entireRadio.click();
            return true;
          }}
          return false;
        }});
        results.watermark_entire_video_selected = radioSelected;
        console.log("Entire video radio selected:", radioSelected);
      }} catch (e) {{
        console.log("Watermark upload error:", e.message);
        results.errors.push("Watermark: " + e.message);
      }}

      await page.waitForTimeout(1500);

      // 4. Set Description
      try {{
        console.log("Setting Description...");
        const descText = {json.dumps(DESCRIPTION_TEXT)};
        const descSet = await page.evaluate((val) => {{
          const tb = document.querySelector('div#textbox');
          if (tb) {{
            tb.focus();
            tb.innerText = val;
            tb.dispatchEvent(new Event('input', {{ bubbles: true }}));
            tb.dispatchEvent(new Event('change', {{ bubbles: true }}));
            return true;
          }}
          return false;
        }}, descText);
        results.description_set = descSet;
        console.log("Description set result:", descSet);
      }} catch (e) {{
        console.log("Description error:", e.message);
        results.errors.push("Description: " + e.message);
      }}

      await page.waitForTimeout(2000);
      await page.screenshot({{ path: {json.dumps(SCREENSHOT_STAGED)} }});

      // 5. Click '게시 (Publish)'
      try {{
        console.log("Clicking Publish button...");
        const publishResult = await page.evaluate(() => {{
          const btns = Array.from(document.querySelectorAll('button, tp-yt-paper-button, ytcp-button, [role="button"]'));
          const pubBtn = btns.find(b => {{
            const t = (b.innerText || b.getAttribute('aria-label') || '').trim();
            return t === '게시' || t === 'Publish' || b.id === 'publish-button';
          }});
          if (pubBtn) {{
            pubBtn.click();
            return true;
          }}
          return false;
        }});
        results.publish_clicked = publishResult;
        console.log("Publish button clicked:", publishResult);

        // Wait 5 seconds for save to process
        await page.waitForTimeout(5000);

        // Get toast notification
        const toast = await page.evaluate(() => {{
          const el = document.querySelector('ytcp-toast, #toast, [role="status"]');
          return el ? el.innerText.trim() : "";
        }});
        results.toast_message = toast;
        console.log("Toast message after publish:", toast);
      }} catch (e) {{
        console.log("Publish error:", e.message);
        results.errors.push("Publish: " + e.message);
      }}

      await page.screenshot({{ path: {json.dumps(SCREENSHOT_AFTER)} }});

      // 6. View public channel page
      try {{
        console.log("Navigating to public channel view: https://www.youtube.com/@SUN-ONEAON");
        await page.goto("https://www.youtube.com/@SUN-ONEAON", {{ waitUntil: "networkidle", timeout: 30000 }});
        await page.waitForTimeout(3000);
        await page.screenshot({{ path: {json.dumps(SCREENSHOT_PUBLIC)} }});
        const pubUrl = (typeof page.url === 'function') ? page.url() : (page.url || '');
        results.public_url = (typeof pubUrl === 'string') ? pubUrl : (pubUrl.href || String(pubUrl));
      }} catch (e) {{
        console.log("Public view navigation error:", e.message);
        results.errors.push("Public view: " + e.message);
      }}

      process.stdout.write('\\nS1EGO_JSON::' + JSON.stringify({{ ok: true, results }}) + '\\n');
    }} catch (e) {{
      process.stdout.write('\\nS1EGO_JSON::' + JSON.stringify({{ ok: false, err: String(e.message || e) }}) + '\\n');
    }} finally {{
      await safeHandOff(currentTask);
    }}
    """

    res = s1_ego.run_ego_js(js, timeout=120)
    return res

if __name__ == "__main__":
    print("=== [STARTING LIVE YOUTUBE STUDIO BRANDING DEPLOYMENT] ===")
    res = run_branding_deployment()
    print("Deployment Result:", json.dumps(res, ensure_ascii=False, indent=2))
